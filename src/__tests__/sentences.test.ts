import { splitSentences } from '../features/voice/core/sentences';

describe('splitSentences — แบ่งคำตอบให้ TTS พูดประโยคแรกได้เร็ว', () => {
  test('ข้อความว่าง = ไม่มีชิ้น', () => {
    expect(splitSentences('   ')).toEqual([]);
  });

  test('ไม่มีตัวจบประโยค (ไทยทั่วไป) = คืนทั้งก้อนชิ้นเดียว', () => {
    const t = 'ว่าไงลูกพี่บอส ดึกป่านนี้ยังไม่นอนอีกเรอะ';
    expect(splitSentences(t)).toEqual([t]);
  });

  test('แบ่งที่จุด/เครื่องหมายคำถาม และขึ้นบรรทัดใหม่', () => {
    const out = splitSentences('สวัสดีครับบอส วันนี้มีอะไรให้ช่วยไหม? ผมพร้อมแล้วนะ. ลุยกันเลย');
    expect(out.length).toBeGreaterThan(1);
    // ประโยคแรกต้องมาก่อนและไม่กลืนทั้งก้อน
    expect(out[0]).toContain('สวัสดีครับบอส');
    expect(out[out.length - 1]).toContain('ลุยกันเลย');
    // รวมกลับต้องได้ใจความเดิมครบ (ตัวอักษรไม่หาย)
    expect(out.join(' ').replace(/\s+/g, '')).toBe(
      'สวัสดีครับบอส วันนี้มีอะไรให้ช่วยไหม? ผมพร้อมแล้วนะ. ลุยกันเลย'.replace(/\s+/g, ''),
    );
  });

  test('ไม่แบ่งที่ช่องว่างระหว่างคำ (ภาษาไทยเว้นวรรคในประโยคเดียวได้)', () => {
    // มีเว้นวรรคหลายจุดแต่ไม่มีตัวจบประโยค → ต้องไม่ถูกหั่นเป็นคำ ๆ
    expect(splitSentences('ปรับ เสียง ให้ หน่อย นะ ครับ')).toEqual([
      'ปรับ เสียง ให้ หน่อย นะ ครับ',
    ]);
  });

  test('เศษประโยคสั้น ๆ ถูกรวมกับชิ้นถัดไป (กันพูดกระท่อนกระแท่น)', () => {
    const out = splitSentences('ได้. ครับ. เดี๋ยวจัดการให้เลยนะครับบอส', 12);
    // "ได้." + "ครับ." สั้นเกิน → รวมกันก่อน
    expect(out[0]).toContain('ได้');
    expect(out[0]).toContain('ครับ');
    expect(out.every((c) => c.trim().length > 0)).toBe(true);
  });
});
