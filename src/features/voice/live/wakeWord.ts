/**
 * @file คำปลุก (wake word) ของโหมดเฝ้า — ขึ้นต้นประโยคด้วยชื่อ persona ตัวไหนก็ได้ ("อัลตรอน ปรับเสียง 30")
 *
 * มีไว้เพราะตอนแอปอยู่เบื้องหลัง ไมค์ได้ยินทุกอย่างรอบตัว (ทีวี คนคุยกัน) — ถ้าไม่มีคำปลุก ทุกประโยคจะกลายเป็นคำสั่ง
 * ตรวจหลังถอดเสียงแล้ว (ไม่มี hotword engine บนเครื่อง ต้องเพิ่ม dependency) → STT ยังถูกเรียกทุกประโยคที่ดังพอ
 * ชื่อสะกดหลายแบบเพราะ STT ถอดไม่ตรงกัน (จาร์วิส/จาวิส, ไฟรเดย์/ฟรายเดย์) — ชุดเดียวกับ RuleClassifier
 * ไม่สลับ persona ตามชื่อที่เรียก: ตอบด้วย persona ที่เปิดอยู่ (สลับต้องสั่ง "เปลี่ยนเป็น…" ตามปกติ)
 */

const NAMES = String.raw`อะตอม|atom|จาร์วิส|จาวิส|jarvis|ไฟรเดย์|ฟรายเดย์|friday|อัลตรอน|อันตรอน|ultron`;
/** คำเรียกนำหน้าที่คนพูดติดปาก ("เฮ้ อัลตรอน", "นี่ อะตอม") */
const CALL = String.raw`(?:เฮ้|เฮ|hey|ok|โอเค|นี่|ไอ้)?`;
const WAKE = new RegExp(
  `^[\\s"'“‘]*${CALL}\\s*(?:${NAMES})(?:\\s*(?:ครับ|ค่ะ|คะ|จ๋า))?[\\s"'”’,，.!:]*`,
  'i',
);

/** ข้อความหลังคำปลุก · null = ไม่ได้ขึ้นต้นด้วยคำปลุก · "" = เรียกชื่อเฉย ๆ ไม่มีคำสั่ง */
export function stripWakeWord(text: string): string | null {
  const match = text.match(WAKE);
  if (!match) return null;
  return text.slice(match[0].length).trim();
}
